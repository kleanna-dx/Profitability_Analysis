-- =========================================================
-- 021_clear_default_remark.sql
-- 목적: batch_schedule.remark의 자동 기본값('매일 06:00') 제거
-- 배경: 사용자 요구사항 — 비고는 빈칸으로 두고, 진짜 캘린더 UI에서 날짜만 선택하도록 함
-- 멱등: '매일 06:00' 또는 '매월 .* 일' 형태의 자동 생성된 기본 remark만 NULL로 정리
--       (사용자가 직접 입력한 다른 메모는 건드리지 않음)
-- =========================================================

UPDATE batch_schedule
   SET remark = NULL
 WHERE remark IN ('매일 06:00', '매일 06:00:00')
    OR remark REGEXP '^매월 [0-9]+일?( [0-9:]+)?$';
